"""Build results/summary.md from the result CSVs (values copied programmatically)."""
import math

import pandas as pd

import config

TABLE_COLS = ["mAP50", "mAP50_95", "recall_025", "precision_025", "mean_conf_tp",
              "signed_cal_gap", "recoverable_share"]
DECIMALS = 4


def _fmt(v):
    if isinstance(v, float):
        return "NaN" if math.isnan(v) else f"{v:.{DECIMALS}f}"
    return str(v)


def md_table(df):
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(_fmt(v) for v in row) + " |")
    return "\n".join(lines)


def main():
    r = config.RESULTS_DIR
    table = pd.read_csv(config.TABLE_FILE)
    box = pd.read_csv(r / "box_level.csv")
    sections = [
        ("All conditions (results/table.csv)", table[["condition", "n_images"] + TABLE_COLS]),
        ("Box level, TP vs FP AUROC (results/box_level.csv)", box[["condition", "auroc_conf", "auroc_cons"]]),
        ("Attack summary (results/attack_summary.csv)", pd.read_csv(r / "attack_summary.csv")),
        ("Recall at conf >= 0.25 per view (results/attack_views.csv)", pd.read_csv(r / "attack_views.csv")),
        ("Attack detection AUROC, pgd_eps8 = positive (results/attack_detection.csv)",
         pd.read_csv(r / "attack_detection.csv")),
    ]
    out = ["# detconf: frozen preliminary results", "",
           f"Generated by `summarize.py` from the CSV files in `results/`; values rounded to "
           f"{DECIMALS} decimals. NaN = undefined (e.g. no detections at conf >= 0.25). "
           "AUROCs are raw: below 0.5 means low values of the signal indicate the positive class.", ""]
    for title, df in sections:
        out += [f"## {title}", "", md_table(df), ""]
    path = r / "summary.md"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"Wrote {path} ({len(table)} conditions)")


if __name__ == "__main__":
    main()
